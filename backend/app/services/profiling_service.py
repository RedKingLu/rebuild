"""P1 profiling (建档) identification service (R17.5 P1 WP-1).

The P1 stage is a target-driven Node Worker Agent loop (AGENTS §2.3), exactly like
P0: deterministic code only *gathers* facts (list files / structure / case-insensitive
candidates / dependency manifest raw contents / config raw / test contents — redacted);
IDENTIFICATION — primary language / tech stack / framework / dependency judgement /
entry-point判定 / config interpretation / infra解读 / module business semantics /
盲区自我发声 — is done by the LLM (Node Worker Agent) via ModelGateway (D-098, no
hardcoded model/endpoint). Mirrors the P0 IntakeService 范式 (do NOT另造框架, D-065):
LLM is REQUIRED — no available model → status="blocked" (reason=no_model_key), NO
rule-based fallback (D-097/公理3).

WP-2 (P1-ARCH-1): P1 REUSES the upstream P0 产物 — P0's LLM-produced intake
identification (primary_language / environment clues / DB / availability) + source_index
— and DEEPENS建档 on top of it. It MUST NOT recompute from scratch or overturn the P0
conclusion silently (病灶: P0 判 C#，旧 P1 确定性误判 JS). If new P1 evidence genuinely
contradicts P0, the model must voice it explicitly in `uncertainty`, not silently flip.

The general field ANCHORS are a stable platform schema; the field VALUES (sample层) are
generated by the LLM per project — never hardcoded sample values (§2.3, §10-26). Missing
fields are honestly recorded as null + reason; blind spots are actively voiced (公理3).
"""

