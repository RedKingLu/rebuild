@dataclass
class IntakeResult:
    status: str                       # completed / blocked / failed
    reason: str = ""
    identification: dict = field(default_factory=dict)   # LLM-produced identification fields
    model_used: Optional[str] = None
    evidence: list = field(default_factory=list)
    context_refs: list = field(default_factory=list)
    skill_refs: list = field(default_factory=list)
    # 模型全失败强制中断时的「已尝试模型链路」+ 结构化错误分类 + 用户可采取操作（透传前端）。
    attempted_chain: list = field(default_factory=list)
    model_error_category: str = ""
    model_user_actions: list = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "status": self.status,
            "reason": self.reason,
            "identification": self.identification,
            "model_used": self.model_used,
            "evidence": self.evidence,
            "context_refs": self.context_refs,
            "skill_refs": self.skill_refs,
            "attempted_chain": self.attempted_chain,
            "model_error_category": self.model_error_category,
            "model_user_actions": self.model_user_actions,
        }


class IntakeService:
    """P0 identification via ModelGateway. `gateway` injectable for tests (blocked
    path + parsing without a live LLM), mirroring AssessmentService (no mock in the
    production path)."""

    def __init__(self, *, gateway=None, tracer=None, auditor=None):
        self._gateway = gateway
        self.tracer = tracer
        self.auditor = auditor

    def _get_gateway(self):
        if self._gateway is not None:
            return self._gateway
        from app.dependencies import get_services
        return get_services().model_gateway

    async def identify(
        self,
        project_id: str,
        *,
        facts: dict,
        run_id: Optional[str] = None,
        stage: str = "p0",
        strategy_id: str = "system-default",
        system_prompt: Optional[str] = None,
        skill_body: str = "",
        context_package: Optional[dict] = None,
    ) -> IntakeResult:
        """Run the P0 identification. Returns IntakeResult (status ∈ completed/blocked/failed).

        `facts` is the deterministic收集事实包 (source_index summary + redacted key-file
        contents + git meta + SQL meta + migration intent/target). The assembled
        `system_prompt` (C0-C6 governance/product/architecture) and `skill_body`
        (P-codebase-onboarding SKILL.md) are combined with the P0 identification output
        contract so the model receives unified context AND the strict JSON schema.
        """
        gw = self._get_gateway()

        # WP-5 (Q-R10-2扩展 P0): no available model → blocked, no rule fallback. 就绪度
        # 预检给出候选模型链路，即便一次调用都未发生也让前端显式看到考察过的模型链路。
        readiness = gw.stage_model_readiness(strategy_id=strategy_id, project_id=project_id,
                                             require_tool_calling=True)
        if not readiness.get("available"):
            self._trace("P0 intake blocked: no model", project_id, run_id, stage)
            return IntakeResult(
                status="blocked",
                reason=("no_model_key: P0 识别需要 LLM 支持，请配置有效 API Key（P0 不降级为规则识别）"
                        f"；{readiness.get('reason','')}"),
                attempted_chain=readiness.get("attempted_chain", []),
                model_error_category="model_unavailable",
                model_user_actions=readiness.get("user_actions", []))

        context_refs, skill_refs = self._context_refs(context_package)
        # system content: 统一上下文（若有）+ Skill 正文（若有）+ P0 识别输出契约（契约放最后，
        # 保证 JSON schema 指令不被冲淡）。
        head_parts = [p for p in (system_prompt, skill_body) if p]
        system_content = ("\n\n---\n\n".join(head_parts) + "\n\n---\n\n" + _SYSTEM_PROMPT
                          if head_parts else _SYSTEM_PROMPT)

        # 批2 (D-110): P0 从单次 chat → 工具循环 Node Worker Agent。事实包仍作为 user 提示帮助，
        # 但 agent 可按需 list_files/code_grep/fs_read 探读真实源、多轮推理，末轮产出结构化识别
        # 契约（契约不变，D-108）。走 call_stream 天然读项目模型选择（global_model_ref）。
        from app.services.stage_agent_loop import run_stage_tool_loop
        loop = await run_stage_tool_loop(
            gw, system_content=system_content, user_content=self._build_user_prompt(facts),
            project_id=project_id, run_id=run_id or "", stage=stage,
            strategy_id=strategy_id, max_tokens=_INTAKE_MAX_TOKENS, temperature=0.3,
            tracer=self.tracer)
        if loop["status"] != "completed":
            reason = loop.get("error_message") or loop.get("error_category") or "model_call_failed"
            self._trace(f"P0 intake model call not completed: {reason}", project_id, run_id, stage)
            return IntakeResult(status="failed", reason=str(reason),
                                model_used=loop.get("model_used"),
                                attempted_chain=loop.get("attempted_chain", []),
                                model_error_category=loop.get("error_category", "model_unavailable"),
                                model_user_actions=_MODEL_USER_ACTIONS)

        parsed = self._parse(loop.get("content", ""))
        model_used = loop.get("model_used")
        # ── 解析失败守卫（`B-ACC-P0-PARSEERROR-STILL-ACCEPTED` 解除条件 ①）────────────
        # 真实规模真跑实测：识别输出不可解析时本方法此前**无条件** return status="completed"，
        # 于是 12 个识别键全落 null、阶段却报 `verdict: accepted / issues: []` —— 把"不可用"
        # 谎报为"可用"。参照实现是 P2 侧 `stage_handlers.py` 的 `unparseable_output` 守卫
        # （同一失败模式，P2 有守卫、P0 没有）。
        # 这里返回**非完成态**：图编排据此触发真返工 —— ValidationAgent 见 declared !=
        # "completed" 即 passed=False（`validation_agent.py` 的综合裁决），ReviewPass 因此重跑
        # 一轮 WorkAgent（真的重新识别，不是只记一笔），仍不通过才升级为 Gate。
        # reason 前缀 `unparseable_output:` 与既有 `no_model_key:` 同范式（机器可判、人可读）；
        # **不含** "no_model_key" 字样、attempted_chain 留空 ⇒ 不会被误判为模型全失败中断。
        # identification 原样带出（含 parse_error / raw / parse_diagnosis），使失败现场能直接
        # 指认"是不是被截断"，而不是只留一句"解析失败"。
        # ⚠ 有意**不设** `model_error_category="output_contract_parse_error"`：该分类会让
        # `stage_retry.is_transient_stage_failure()` 把本次失败判为可重试，于是整个 P0 阶段会先被
        # 自动重跑最多 2 次（`STAGE_TRANSIENT_MAX_RETRIES`），再叠加 ReviewPass 的 2 轮返工 ⇒ 最坏
        # 6 次完整 P0（每次都是真实 LLM 成本）。ReviewPass 的返工已经覆盖"重试结构化输出"这一诉求，
        # 故不再叠加阶段级重试。若将来判定 P0 也应像 P3 那样走阶段级重试，须连同成本一并评估后再加。
        if parsed.get("parse_error"):
            diagnosis = parsed.get("parse_diagnosis") or {}
            truncated = bool(diagnosis.get("suspected_truncation"))
            self._trace("P0 intake identification unparseable（非完成态，触发返工）",
                        project_id, run_id, stage)
            return IntakeResult(
                status="failed",
                reason=("unparseable_output: P0 识别输出无法解析为结构化 JSON"
                        f"（疑似截断={truncated}；诊断见 identification.parse_diagnosis）"
                        "——不得据此判阶段完成（D-097/公理3）"),
                identification=parsed, model_used=model_used,
                context_refs=context_refs, skill_refs=skill_refs)
        # 目标运行环境是用户输入采集（非识别），由采集直接透传进 intake（migration_target）。
        parsed.setdefault("migration_target", facts.get("migration_target"))
        self._trace("P0 intake completed (LLM identification)", project_id, run_id, stage)
        return IntakeResult(
            status="completed", identification=parsed, model_used=model_used,
            context_refs=context_refs, skill_refs=skill_refs,
        )

    @staticmethod
    def _context_refs(context_package: Optional[dict]) -> tuple[list, list]:
        if not context_package:
            return [], []
        trace = context_package.get("assembly_trace", {}) or {}
        context_refs = list(trace.get("layers_assembled", []))
        skill_refs = [s.get("skill_id") or s.get("name")
                      for s in (context_package.get("skills") or [])
                      if s.get("skill_id") or s.get("name")]
        return context_refs, skill_refs

    def _build_user_prompt(self, facts: dict) -> str:
        """Build the user message from the deterministic收集事实包 (bounded, redacted)."""
        # facts is already redacted/bounded by the caller (RealP0Handler collection).
        blob = json.dumps(facts, ensure_ascii=False, default=str)
        if len(blob) > 24000:      # 采集事实包上限，防超长（诚实截断并声明）
            blob = blob[:24000] + '\n…[事实包超长已截断，请就已给事实推理并在 uncertainty 中声明截断]'
        return (
            "以下是平台确定性工具采集的目标项目【事实包】（已脱敏、已按大小写不敏感列举、依赖/入口"
            "为全候选交你判定）。请据此完成 P0 接入识别，严格输出上述 JSON。\n\n"
            f"事实包：\n{blob}\n\n"
            "要求：key_files/entry_points 只能引用事实包中真实存在的候选路径（勿杜撰）；样本值全部来自"
            "事实包推理；缺失诚实标 null + 原因；主动在 uncertainty 中发声识别盲区。"
        )

    def _parse(self, content: str) -> dict:
        """Parse the LLM JSON output defensively into the identification fields.

        批2: uses the robust extractor (handles prose-wrapped / fenced JSON from the tool
        loop).

        `B-ACC-P0-PARSEERROR-STILL-ACCEPTED` 解除条件 ③（声称与实现不符的订正）：本 docstring
        原文自称 `Unparseable → honest parse_error marker (NodeLoop ReviewPass retries)`，
        日志原文亦印"（返工重试结构化输出）"—— 但实测**当时并没有那个重试**：`identify()` 无条件
        置 status="completed"，图直接进 Gate。现已改为**真的**返非完成态（见 `identify()` 的解析
        失败守卫），返工由 ValidationAgent → ReviewPass 真实触发。措辞按"实现什么就说什么"订正：
        本方法只负责**产出可诊断的 parse_error 标记**，返工与否由 `identify()` 的守卫与图编排决定。

        V26.2 返工批次二（甲 ②）：本处此前**完全没有截断诊断**，失败现场只能看到"输出非合法
        JSON"，看不出"因为被砍断" —— 这正是验收 agent 把真因误归为"模型输出质量问题"的直接原因。
        现接入共享诊断（`suspected_truncation` / `truncation_signals`）。
        """
        from app.services.stage_agent_loop import extract_json_object
        data = extract_json_object(content)
        if data is not None:
            return data
        text = (content or "").strip()
        diagnosis = _diagnose_parse_failure_shared(
            text, max_tokens=_INTAKE_MAX_TOKENS, timeout_s=_STAGE_TIMEOUT,
            env_knobs="P0_INTAKE_MAX_TOKENS")
        _log_parse_failure(logger, "P0 intake", diagnosis)
        return {"parse_error": True, "raw": text[:2000], "parse_diagnosis": diagnosis}

    def _trace(self, summary: str, project_id, run_id, stage) -> None:
        if self.tracer is None:
            return
        try:
            self.tracer.write("model_call", action="p0_intake", summary=summary,
                              project_id=project_id, run_id=run_id, stage=stage)
        except Exception:
            logger.debug("P0 intake trace 写入失败（advisory）", exc_info=True)


def redact_config_text(text: str) -> str:
    """采集层脱敏（D-032）：连接串值 + api_key/secret/password/token 一律 [REDACTED]。
    用于把关键文件原文喂给 LLM 前的二次防护——绝不把密钥/连接串值送入模型或落盘。"""
    if not text:
        return text
    from app.services.security_authorization import redact_secrets
    out = text
    for pat in _CONN_STRING_PATTERNS:
        out = pat.sub(r"\1[REDACTED]\2", out)
    return redact_secrets(out)
