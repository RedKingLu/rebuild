"""P0 intake identification service (R17.5 WP-1).

The P0 stage is a target-driven Node Worker Agent loop (AGENTS §2.3): deterministic
code only *gathers* facts (clone / list files / read / count / encoding / redact);
IDENTIFICATION — key-file judgement, tech stack / environment interpretation,
availability A/B/C, migration-intent归纳, DB entry/dialect interpretation, entry-point
judgement, P1 task planning, gap自我发声 — is done by the LLM (Node Worker Agent) via
ModelGateway (D-098, no hardcoded model/endpoint). This mirrors the P2 AssessmentService
范式 (R10-2 Q-R10-2): LLM is REQUIRED — no available model → status="blocked"
(reason=no_model_key), NO rule-based fallback (D-097/公理3). An honest blocked beats a
fake rule-derived intake.

The general field ANCHORS are a stable platform schema; the field VALUES (sample层) are
generated by the LLM per project — never hardcoded sample values (§2.3, §10-26). Missing
fields are honestly recorded as null + reason (never fabricated); blind spots are actively
voiced (公理3). Deep business semantics / field-level DB schema stay in P1/P2.
"""

